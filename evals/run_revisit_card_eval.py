"""Offline eval harness comparing rule-based vs LLM-generated Revisit Cards.

Run from the project root (with the venv active):

    python -m evals.run_revisit_card_eval

Without OPENAI_API_KEY set, only the rule-based path is evaluated (the LLM
path is skipped entirely, not run-and-expected-to-fail) — this mirrors how
the API itself behaves when generation_method=llm is requested without a
key available.

This intentionally reuses the *exact* rule-based builder functions and the
LLM prompt/validation from app/services/revisit_card_store.py and
app/services/llm.py, rather than reimplementing the logic here — so this
eval always reflects what the running API actually does, with no risk of
the eval and the production code drifting apart.
"""

import json
import os
import re
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.schemas.capture import Capture, CaptureLabel, SourceType  # noqa: E402
from app.schemas.resource import Resource  # noqa: E402
from app.services import llm  # noqa: E402
from app.services.revisit_card_store import (  # noqa: E402
    _CLUSTER_MIXED_SOURCE_NEXT_ACTION,
    _CLUSTER_NEXT_ACTION_BY_SOURCE_TYPE,
    _MAX_LLM_CONTEXT_CAPTURES,
    _NEXT_ACTION_BY_SOURCE_TYPE,
    _build_cluster_next_action,
    _build_cluster_original_context,
    _build_cluster_title,
    _build_cluster_why_saved,
    _build_next_action,
    _build_original_context,
    _build_resource_section,
    _build_title,
    _build_why_saved,
    _capture_context_item,
    _resource_context_item,
)

_URL_PATTERN = re.compile(r"https?://[^\s)\]\"'>]+")

DATASET_PATH = ROOT / "evals" / "datasets" / "revisit_card_eval.jsonl"
REPORTS_DIR = ROOT / "evals" / "reports"

# Every generic boilerplate string the rule-based path can produce. Used to
# flag too_generic without re-encoding the same strings a second time.
_KNOWN_GENERIC_NEXT_ACTIONS = (
    set(_NEXT_ACTION_BY_SOURCE_TYPE.values())
    | set(_CLUSTER_NEXT_ACTION_BY_SOURCE_TYPE.values())
    | {_CLUSTER_MIXED_SOURCE_NEXT_ACTION}
)

_JUDGE_SYSTEM_PROMPT = """\
You are grading a "Revisit Card" generated by another system from saved
capture(s). You are given the original input context and the generated
card as JSON. Score the card strictly against the rubric below, using ONLY
the provided input context as ground truth — do not reward or penalize
based on outside knowledge of the topic.

Score each dimension 1-5 (integer):
- intent_preservation: does it preserve why the user saved this, given the
  capture's label (casual vs return)?
- context_grounding: does it stay grounded in the provided context, with
  no invented specifics?
- usefulness: would this actually help the user resume the topic later
  with no other memory of it?
- next_action_quality: is next_action specific and doable given the
  available context (not just generically plausible)?
- conciseness: is it clear without being padded or rambling?

Also set these booleans:
- invented_fact: true if the card states any name, number, source, or
  claim not present in the input context.
- missing_next_action: true if next_action is empty/missing.
- too_generic: true if the card is boilerplate that ignores specific
  available context (false if the input context was itself too thin to
  support anything more specific — being appropriately generic given thin
  input is not a flaw).
- empty_or_invalid: true if any required field (title, why_saved,
  original_context, next_action) is missing or not a string.

Return ONLY a JSON object with exactly these keys: intent_preservation,
context_grounding, usefulness, next_action_quality, conciseness,
invented_fact, missing_next_action, too_generic, empty_or_invalid,
rationale (a one-sentence explanation).
"""


@dataclass
class EvalCluster:
    """Stand-in for ClusterORM — just enough attributes for the rule-based
    cluster builders, without needing a database session for eval cases."""

    id: str
    title: Optional[str]


def _capture_from_dict(data: Dict[str, Any]) -> Capture:
    return Capture(
        source_type=SourceType(data["source_type"]),
        label=CaptureLabel(data["label"]),
        title=data.get("title"),
        user_note=data.get("user_note"),
        selected_text=data.get("selected_text"),
        extracted_text=data.get("extracted_text"),
        url=data.get("url"),
    )


def _resources_from_dicts(cluster_id: str, data: List[Dict[str, Any]]) -> List[Resource]:
    return [
        Resource(
            cluster_id=cluster_id,
            url=r["url"],
            title=r["title"],
            snippet=r.get("snippet"),
            validation_score=r.get("validation_score"),
        )
        for r in data
    ]


def _allowed_urls_for_case(case: Dict[str, Any]) -> Set[str]:
    """URLs the card is allowed to mention — its own capture(s)' urls plus
    any provided resources' urls. Anything else appearing in a generated
    card is an invented URL.
    """
    ctx = case["input_context"]
    urls: Set[str] = set()
    if case["case_type"] == "individual":
        url = ctx["capture"].get("url")
        if url:
            urls.add(url)
    else:
        for c in ctx.get("captures", []):
            if c.get("url"):
                urls.add(c["url"])
        for r in ctx.get("resources", []):
            if r.get("url"):
                urls.add(r["url"])
    return urls


def load_dataset(path: Path) -> List[Dict[str, Any]]:
    cases = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                cases.append(json.loads(line))
    return cases


def generate_rule_based_card(case: Dict[str, Any]) -> Dict[str, Optional[str]]:
    ctx = case["input_context"]
    if case["case_type"] == "individual":
        capture = _capture_from_dict(ctx["capture"])
        return {
            "title": _build_title(capture),
            "why_saved": _build_why_saved(capture),
            "original_context": _build_original_context(capture),
            "next_action": _build_next_action(capture),
        }

    captures = [_capture_from_dict(c) for c in ctx["captures"]]
    cluster = EvalCluster(id=case["case_id"], title=ctx.get("cluster_title"))
    resources = _resources_from_dicts(case["case_id"], ctx.get("resources", []))

    original_context = _build_cluster_original_context(captures)
    resource_section = _build_resource_section(resources)
    if resource_section:
        original_context = (
            f"{original_context}\n\n{resource_section}"
            if original_context
            else resource_section
        )

    return {
        "title": _build_cluster_title(cluster, captures),
        "why_saved": _build_cluster_why_saved(captures),
        "original_context": original_context,
        "next_action": _build_cluster_next_action(captures),
    }


def generate_llm_card(case: Dict[str, Any]) -> Optional[Dict[str, str]]:
    ctx = case["input_context"]
    if case["case_type"] == "individual":
        capture = _capture_from_dict(ctx["capture"])
        llm_context = {
            "card_kind": "individual",
            "captures": [_capture_context_item(capture)],
        }
    else:
        captures = [_capture_from_dict(c) for c in ctx["captures"]]
        resources = _resources_from_dicts(case["case_id"], ctx.get("resources", []))
        llm_context = {
            "card_kind": "cluster",
            "cluster_title": ctx.get("cluster_title"),
            "captures": [
                _capture_context_item(c) for c in captures[:_MAX_LLM_CONTEXT_CAPTURES]
            ],
        }
        if resources:
            llm_context["resources"] = [_resource_context_item(r) for r in resources]
    return llm.generate_revisit_card_content(
        llm_context, owner_type="eval", owner_id=case["case_id"]
    )


def run_deterministic_checks(
    card: Optional[Dict[str, Any]],
    expected: Dict[str, Any],
    allowed_urls: Optional[Set[str]] = None,
) -> Dict[str, Any]:
    flags = {
        "empty_or_invalid": False,
        "missing_next_action": False,
        "too_generic": False,
        "invented_fact": False,
    }
    notes: List[str] = []

    if card is None:
        flags["empty_or_invalid"] = True
        notes.append("card generation returned no result")
        return {"flags": flags, "passed": False, "notes": notes}

    for field_name in ("title", "why_saved", "next_action"):
        value = card.get(field_name)
        if not isinstance(value, str) or not value.strip():
            flags["empty_or_invalid"] = True
            notes.append(f"{field_name} is missing or empty")

    next_action = (card.get("next_action") or "").strip()
    if not next_action:
        flags["missing_next_action"] = True

    if (
        not expected.get("allow_generic_next_action", True)
        and next_action in _KNOWN_GENERIC_NEXT_ACTIONS
    ):
        flags["too_generic"] = True
        notes.append("next_action matches known generic boilerplate")

    haystack_raw = " ".join(
        str(card.get(f) or "")
        for f in ("title", "why_saved", "original_context", "next_action")
    )
    haystack = haystack_raw.lower()
    for term in expected.get("forbidden_terms", []):
        if term.lower() in haystack:
            flags["invented_fact"] = True
            notes.append(f"forbidden term found: {term!r}")

    found_urls = {u.rstrip(".,;:") for u in _URL_PATTERN.findall(haystack_raw)}
    invented_urls = found_urls - (allowed_urls or set())
    if invented_urls:
        flags["invented_fact"] = True
        notes.append(f"invented URL(s) not in provided context/resources: {sorted(invented_urls)}")

    passed = not any(flags.values())
    return {"flags": flags, "passed": passed, "notes": notes}


def judge_card(case: Dict[str, Any], card: Optional[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
    """Optional LLM-as-judge scoring. Returns None if no API key, or if the
    judge call itself fails — judge scores are advisory and never gate the
    eval's pass/fail outcome, only the deterministic checks do that.
    """
    if card is None or not os.environ.get("OPENAI_API_KEY"):
        return None

    try:
        from openai import OpenAI

        client = OpenAI()
        response = client.chat.completions.create(
            model=llm.get_active_model_name(),
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": _JUDGE_SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": json.dumps(
                        {"input_context": case["input_context"], "generated_card": card}
                    ),
                },
            ],
        )
        return json.loads(response.choices[0].message.content)
    except Exception as exc:
        return {"error": type(exc).__name__}


def _summarize(results: List[Dict[str, Any]]) -> Dict[str, Any]:
    def rate(method: str) -> Optional[Dict[str, Any]]:
        subset = [r for r in results if r["generation_method"] == method]
        if not subset:
            return None
        passed = sum(1 for r in subset if r["deterministic_check_results"]["passed"])
        return {
            "count": len(subset),
            "passed": passed,
            "pass_rate": round(passed / len(subset), 3),
        }

    flag_counts = {
        "invented_fact": 0,
        "missing_next_action": 0,
        "too_generic": 0,
        "empty_or_invalid": 0,
    }
    for r in results:
        for flag, value in r["deterministic_check_results"]["flags"].items():
            if value:
                flag_counts[flag] += 1

    return {
        "rule_based": rate("rule_based"),
        "llm": rate("llm"),
        "flag_counts": flag_counts,
    }


def main() -> None:
    cases = load_dataset(DATASET_PATH)
    has_openai_key = bool(os.environ.get("OPENAI_API_KEY"))
    eval_timestamp = datetime.now(timezone.utc).isoformat()

    results: List[Dict[str, Any]] = []
    for case in cases:
        expected = case.get("expected_properties", {})
        allowed_urls = _allowed_urls_for_case(case)

        rule_card = generate_rule_based_card(case)
        rule_checks = run_deterministic_checks(rule_card, expected, allowed_urls)
        results.append(
            {
                "case_id": case["case_id"],
                "case_type": case["case_type"],
                "generation_method": "rule_based",
                "model_name": None,
                "prompt_version": None,
                "generated_card": rule_card,
                "deterministic_check_results": rule_checks,
                "judge_scores": judge_card(case, rule_card) if has_openai_key else None,
            }
        )

        if has_openai_key:
            llm_card = generate_llm_card(case)
            llm_checks = run_deterministic_checks(llm_card, expected, allowed_urls)
            results.append(
                {
                    "case_id": case["case_id"],
                    "case_type": case["case_type"],
                    "generation_method": "llm",
                    "model_name": llm.get_active_model_name() if llm_card else None,
                    "prompt_version": llm.PROMPT_VERSION if llm_card else None,
                    "generated_card": llm_card,
                    "deterministic_check_results": llm_checks,
                    "judge_scores": judge_card(case, llm_card),
                }
            )

    summary = _summarize(results)

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    slug = eval_timestamp.replace(":", "").replace("+00:00", "Z")
    report_path = REPORTS_DIR / f"revisit_card_eval_{slug}.json"
    report = {
        "eval_timestamp": eval_timestamp,
        "dataset_path": str(DATASET_PATH.relative_to(ROOT)),
        "num_cases": len(cases),
        "openai_api_key_present": has_openai_key,
        "summary": summary,
        "results": results,
    }
    report_path.write_text(json.dumps(report, indent=2))

    print(f"Cases evaluated: {len(cases)}")
    rb = summary["rule_based"]
    print(f"Rule-based pass rate: {rb['passed']}/{rb['count']} ({rb['pass_rate']:.0%})")
    if summary["llm"] is not None:
        lm = summary["llm"]
        print(f"LLM pass rate:        {lm['passed']}/{lm['count']} ({lm['pass_rate']:.0%})")
    else:
        print("LLM pass rate:        skipped (OPENAI_API_KEY not set)")
    print("Flag counts (across all generated cards):")
    for flag, count in summary["flag_counts"].items():
        print(f"  {flag}: {count}")
    print(f"\nReport saved to: {report_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
